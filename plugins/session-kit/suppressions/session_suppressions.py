"""The reasons beside a project's suppressions, and the index that lists them for review.

A suppression (the noqa and ignore comments of ruff, mypy and pyright, the
ts-ignore and expect-error directives, the eslint, oxlint and biome disables,
and the any and unknown casts) carries its reason in place: a comment on its
line, after the marker and its codes, or on the line above, of three words
or more. ``session-suppressions list`` prints every marker in the tree's
source files with its reason, ``index`` writes the index (``docs/suppressions.md``,
a table of where, marker and reason) for the owner to review, and ``check``
prints one line per problem and exits 1: a marker without a reason, and an
index that is missing or stale. ``.claude/claude-kit.json`` may set, under
``suppressions``, the ``index`` path and the ``skip`` directories. A rule
relaxed in a config file is outside this check. Prose files, the index
itself, dependencies and virtual environments (a directory holding
``pyvenv.cfg`` or named ``site-packages``) are never read for markers. A
marker inside a string or a docstring is a mention, a test's fixture or a
reader's pattern, and is no site: Python files are read through the
tokenizer and only their comments are searched, and in a TypeScript or
JavaScript file the string literals of a line are dropped before the search,
with a directive counted only in the line's comment.
"""

from __future__ import annotations

import argparse
import io
import json
import re
import sys
import tokenize
from dataclasses import dataclass
from pathlib import Path

SOURCE_SUFFIXES = {".py", ".pyi", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".cts"}
SKIP_DIRS = {".git", "node_modules", ".venv", "venv", "dist", "build", "__pycache__", ".direnv", ".ruff_cache", ".pytest_cache"}
DEFAULT_INDEX = "docs/suppressions.md"
MIN_WORDS = 3

# Each marker's pattern is built from pieces, so this file holds none of them whole.
MARKERS: list[tuple[str, re.Pattern[str]]] = [
    ("noqa", re.compile("#" + r"\s*(?:ruff:\s*)?" + "noqa" + r"\b")),
    ("type: " + "ignore", re.compile("#" + r"\s*type:\s*" + "ignore" + r"\b")),
    ("pyright: " + "ignore", re.compile("#" + r"\s*pyright:\s*" + "ignore" + r"\b")),
    ("@ts-" + "ignore", re.compile("@ts-" + "ignore" + r"\b")),
    ("@ts-" + "expect-error", re.compile("@ts-" + "expect-error" + r"\b")),
    ("eslint-" + "disable", re.compile("eslint-" + "disable")),
    ("oxlint-" + "disable", re.compile("oxlint-" + "disable")),
    ("biome-" + "ignore", re.compile("biome-" + "ignore")),
    ("as " + "any", re.compile(r"\bas\s+" + "any" + r"\b")),
    ("as unknown " + "as", re.compile(r"\bas\s+unknown\s+" + "as" + r"\b")),
]
CODE = r"(?:\[[^\]]*\]|[A-Z]+\d+|[a-z0-9]+(?:[-/@][\w-]+)+|\d+)"
CODES = re.compile(rf"^[\w-]*[\s:,]*{CODE}?(?:\s*,\s*{CODE})*[\s:,.-]*")
"""What follows a marker before its reason: the rest of its own token, then its codes."""
WORD = re.compile(r"[A-Za-z]{2,}")
INTRO = (
    "# Suppressions\n\n"
    "Generated by `session-suppressions index` from the markers in the tree's source files: "
    "every suppression and type escape with the reason written beside it, for review. "
    "Do not edit by hand: the check fails when it is stale.\n\n"
    "| Where | Marker | Why |\n| --- | --- | --- |\n"
)


@dataclass
class Settings:
    index: str = DEFAULT_INDEX
    skip: frozenset[str] = frozenset(SKIP_DIRS)


@dataclass
class Site:
    path: Path
    line: int
    marker: str
    reason: str


def read_settings(root: Path) -> Settings:
    settings = Settings()
    try:
        parsed = json.loads((root / ".claude" / "claude-kit.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return settings
    block = parsed.get("suppressions") if isinstance(parsed, dict) else None
    if not isinstance(block, dict):
        return settings
    if isinstance(block.get("index"), str) and block["index"]:
        settings.index = block["index"]
    if isinstance(block.get("skip"), list):
        settings.skip = frozenset(SKIP_DIRS | {s for s in block["skip"] if isinstance(s, str)})
    return settings


def is_environment(directory: Path) -> bool:
    """A virtual environment or an installed package tree, whatever it is named."""
    return directory.name == "site-packages" or (directory / "pyvenv.cfg").is_file()


def source_files(root: Path, settings: Settings) -> list[Path]:
    index = (root / settings.index).resolve()
    out: list[Path] = []
    pending = [root]
    while pending:
        directory = pending.pop()
        for path in sorted(directory.iterdir()):
            if path.is_dir():
                if path.name not in settings.skip and not is_environment(path):
                    pending.append(path)
            elif path.suffix in SOURCE_SUFFIXES and path.resolve() != index:
                out.append(path)
    return sorted(out)


COMMENT_MARKERS = {name for name, _ in MARKERS if name.startswith(("@ts-", "eslint-", "oxlint-", "biome-"))}
STRINGS = re.compile(r"'(?:\\.|[^'\\\n])*'|\"(?:\\.|[^\"\\\n])*\"|`(?:\\.|[^`\\])*`")


def python_comments(text: str) -> dict[int, str]:
    """Each comment of a Python file by its line, through the tokenizer; every line on a tokenize error."""
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, SyntaxError):
        return {n + 1: line for n, line in enumerate(text.splitlines())}
    return {tok.start[0]: tok.string for tok in tokens if tok.type == tokenize.COMMENT}


def script_parts(line: str) -> tuple[str, str]:
    """A TypeScript or JavaScript line without its string literals, split into its code and its comment."""
    bare = STRINGS.sub("''", line)
    at = min((i for i in (bare.find("//"), bare.find("/*")) if i >= 0), default=-1)
    return (bare, "") if at < 0 else (bare[:at], bare[at:])


def searchable(path: Path, lines: list[str]) -> dict[int, list[tuple[str, str]]]:
    """Per line, the texts to search and which markers apply to each."""
    if path.suffix in {".py", ".pyi"}:
        return {n: [(comment, "comment")] for n, comment in python_comments("\n".join(lines) + "\n").items()}
    out: dict[int, list[tuple[str, str]]] = {}
    for n, line in enumerate(lines, start=1):
        code, comment = script_parts(line)
        out[n] = [(code, "code"), (comment, "comment")]
    return out


def words_of(text: str) -> str:
    """The text as a reason when it holds enough words, else nothing."""
    cleaned = text.strip().lstrip("#/* ").strip(" :,-")
    return cleaned if len(WORD.findall(cleaned)) >= MIN_WORDS else ""


def reason_after(comment: str, pattern: re.Pattern[str]) -> str:
    """The reason written after the marker and its codes in the same comment."""
    m = pattern.search(comment)
    if not m:
        return ""
    return words_of(CODES.sub("", comment[m.end():], count=1))


def comment_of(parts: dict[int, list[tuple[str, str]]], n: int) -> str:
    return next((text for text, kind in parts.get(n, []) if kind == "comment"), "")


def reason_of(parts: dict[int, list[tuple[str, str]]], n: int, text: str, kind: str, pattern: re.Pattern[str]) -> str:
    """The marker's reason: after it in its comment, in the line's comment, or on the line above."""
    found = reason_after(text, pattern) if kind == "comment" else ""
    if not found and kind == "code":
        found = words_of(comment_of(parts, n))
    if not found:
        found = words_of(comment_of(parts, n - 1))
    return found


def sites_in(path: Path) -> list[Site]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError):
        return []
    found: list[Site] = []
    parts = searchable(path, lines)
    for n, texts in sorted(parts.items()):
        for text, kind in texts:
            for name, pattern in MARKERS:
                if (name in COMMENT_MARKERS) != (kind == "comment") and path.suffix not in {".py", ".pyi"}:
                    continue
                if pattern.search(text):
                    found.append(Site(path, n, name, reason_of(parts, n, text, kind, pattern)))
    return found


def where(site: Site, root: Path) -> str:
    return f"{site.path.relative_to(root)}:{site.line}"


def describe(site: Site, root: Path) -> str:
    return f"{where(site, root)}  {site.marker}  {site.reason or 'unjustified'}"


def render_index(sites: list[Site], root: Path) -> str:
    rows = [f"| `{where(s, root)}` | `{s.marker}` | {s.reason or 'unjustified'} |" for s in sites]
    return INTRO + "\n".join(rows) + ("\n" if rows else "") + f"\n{len(sites)} suppressions.\n"


def problems(sites: list[Site], root: Path, settings: Settings) -> list[str]:
    out = [f"{where(s, root)}: `{s.marker}` has no reason on its line or the line above" for s in sites if not s.reason]
    index = root / settings.index
    if not index.is_file():
        out.append(f"{settings.index}: missing, run `session-suppressions index`")
    elif index.read_text(encoding="utf-8") != render_index(sites, root):
        out.append(f"{settings.index}: stale, run `session-suppressions index`")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="The reasons beside a project's suppressions, and their index.")
    parser.add_argument("command", choices=("list", "index", "check"))
    parser.add_argument("--root", default=".", help="the project root; its .claude/claude-kit.json applies")
    args = parser.parse_args()
    root = Path(args.root).resolve()
    settings = read_settings(root)
    sites = [s for path in source_files(root, settings) for s in sites_in(path)]
    if args.command == "list":
        for site in sites:
            print(describe(site, root))
        print(f"{len(sites)} suppressions")
        return 0
    if args.command == "index":
        index = root / settings.index
        index.parent.mkdir(parents=True, exist_ok=True)
        index.write_text(render_index(sites, root), encoding="utf-8")
        print(f"{settings.index}: {len(sites)} suppressions")
        return 0
    found = problems(sites, root, settings)
    for p in found:
        print(p)
    if not found:
        print(f"{len(sites)} suppressions, each with its reason, and {settings.index} current")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
